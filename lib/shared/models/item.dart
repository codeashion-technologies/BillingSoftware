    hsnUqc: map['hsn_uqc'] as String,
    rolMin: map['rol_min'] as String,
    rolMax: map['rol_max'] as String,
    openingStockQuantity: map['opening_stock_quantity'] as String,
    openingStockAmount: map['opening_stock_amount'] as String,
    openingStockNos: map['opening_stock_nos'] as String,
    calculateOn: map['calculate_on'] as String,
    rateUpdate: map['rate_update'] as String,
    showInStockReport: map['show_in_stock_report'] as String,
    active: map['active'] as String,
