      purchaseRate,
      mrp,
      cutAverage,
      boxPack,
      looseQuantity;
  final String hsnCode,
      sgst,
      cgst,
      igst,
      gstCalculation,
      hsnDescription,
      hsnUqc;
  final String rolMin,
      rolMax,
      openingStockQuantity,
      openingStockAmount,
      openingStockNos;
  final String calculateOn,
      rateUpdate,
      showInStockReport,
      active,
      discount,
      remarks;

  factory Item.fromMap(Map<String, Object?> map) => Item(
    id: map['id'] as int?,
    firmId: map['firm_id'] as int? ?? 0,
    itemCode: map['item_code'] as String,
    itemName: map['item_name'] as String,
    itemGroup: map['item_group'] as String,
    subGroup: map['sub_group'] as String,
    mfgBy: map['mfg_by'] as String,
    unitOfMeasure: map['unit_of_measure'] as String,
    rateRetail: map['rate_retail'] as String,
    dealerRate: map['dealer_rate'] as String,
    purchaseRate: map['purchase_rate'] as String,
    mrp: map['mrp'] as String,
    cutAverage: map['cut_average'] as String,
    boxPack: map['box_pack'] as String,
    looseQuantity: map['loose_quantity'] as String,
    hsnCode: map['hsn_code'] as String,
    sgst: map['sgst'] as String,
    cgst: map['cgst'] as String,
    igst: map['igst'] as String,
