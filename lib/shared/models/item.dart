    required this.hsnUqc,
    required this.rolMin,
    required this.rolMax,
    required this.openingStockQuantity,
    required this.openingStockAmount,
    required this.openingStockNos,
    required this.calculateOn,
    required this.rateUpdate,
    required this.showInStockReport,
